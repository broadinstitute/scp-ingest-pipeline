import anndata
import pandas as pd
import numpy as np
import scipy.sparse as sp

key = 'cluster_label'
# key = 'leiden'

pseudobulk_profiles = []
cluster_labels = []

for i, k in enumerate(adata.obs[key].unique()):
    # print(f'cluster {k} ({i + 1} / {adata.obs[key].nunique()})')
    # CAS requires raw integer counts; cluster_adata() has already overwritten
    # .X with normalized/log1p/scaled values, so average the raw counts layer.
    pseudobulk_profiles.append(np.array(adata[adata.obs[key] == k].layers['count'].mean(axis=0)).squeeze())
    cluster_labels.append(k)

adata_bulk = anndata.AnnData(
    X=sp.csr_matrix(np.vstack(pseudobulk_profiles)),
    obs=pd.DataFrame(data={key: cluster_labels}),
    var=adata.var,
)
